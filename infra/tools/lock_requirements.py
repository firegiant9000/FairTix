"""Write teardown/requirements.lock: every package the workflows install, pinned and hashed.

    python tools/lock_requirements.py        (run from infra/, in the teardown venv)

The lab workflows install with `pip install --require-hashes -r teardown/requirements.lock`
in jobs that hold `id-token: write`, so no transitive dependency can float. This uses pip
itself (`pip install --dry-run --report`), resolving for the workflows' target: CPython
3.12 on Linux x86-64, wheels only. Standard library only; no new tool.

Re-run it whenever teardown/requirements.txt changes, and commit both files.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

INFRA = Path(__file__).resolve().parents[1]
REQUIREMENTS = INFRA / "teardown" / "requirements.txt"
LOCK = INFRA / "teardown" / "requirements.lock"
TARGET = ["--python-version", "3.12", "--platform", "manylinux2014_x86_64", "--implementation", "cp",
          "--only-binary=:all:"]

HEADER = """\
# Generated by infra/tools/lock_requirements.py from teardown/requirements.txt. Don't edit.
# Resolved for CPython 3.12 on Linux x86-64 (the lab workflows). Every package is a
# pure-Python wheel, so the hashes hold on any platform.
# Install: python -m pip install --require-hashes -r teardown/requirements.lock
"""


def resolve() -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
             *TARGET, "--target", str(Path(tmp) / "target"), "--report", str(report), "-r", str(REQUIREMENTS)],
            check=True,
        )
        return json.loads(report.read_text(encoding="utf-8"))["install"]


def render(install: list[dict]) -> str:
    lines = [HEADER]
    for item in sorted(install, key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        digest = item["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256")
        if not digest:
            raise SystemExit(f"{name} {version}: pip reported no sha256")
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}")
    return "\n".join(lines) + "\n"


def main() -> int:
    LOCK.write_text(render(resolve()), encoding="utf-8", newline="\n")
    print(f"wrote {LOCK.relative_to(INFRA)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
